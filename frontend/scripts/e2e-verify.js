const __dirname = dirname(__filename);

const BASE_URL = 'http://localhost:5173';
const API_URL = 'http://localhost:5000';
const TEST_EMAIL = 'test@lawgpt.local';
const TEST_PASSWORD = 'Password@123';

// Clean text-extractable legal PDF fixture (generated by
// `node backend/scripts/generateTestPdf.js`). The old inline minimal PDF had
// no text stream, so the pipeline marked documents "failed" and AI features
// 400'd with "no processed documents yet".
const FIXTURE_PDF = 'LawGPT-E2E-Writ-Petition.pdf';
const FIXTURE_PDF_PATH = join(__dirname, 'fixtures', FIXTURE_PDF);

const results = [];
let browser, context, page;

function log(step, status, detail = '') {
  const icon = status === 'PASS' ? '✅' : status === 'FAIL' ? '❌' : 'ℹ️';
  const msg = `${icon} [${step}] ${status}${detail ? ' — ' + detail : ''}`;
  console.log(msg);
  results.push({ step, status, detail });
}

async function screenshot(name) {
  const dir = join(__dirname, '..', 'test-screenshots');
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${name}.png`);
  await page.screenshot({ path, fullPage: true });
  return path;
}

async function safeRun(stepName, fn) {
  try {
    await fn();
    return true;
  } catch (err) {
    log(stepName, 'FAIL', err.message?.slice(0, 200));
    await screenshot(`fail-${stepName.replace(/\s+/g, '-').toLowerCase()}`).catch(() => {});
    return false;
  }
}

// ─── SETUP ──────────────────────────────────────────────────────────────

async function setup() {
  browser = await chromium.launch({ headless: true });
  context = await browser.newContext({
    viewport: { width: 1280, height: 800 },
    locale: 'en-US',
  });
  page = await context.newPage();

  // Collect console errors
  page.on('console', (msg) => {
    if (msg.type() === 'error') {
      console.log(`  [console.error] ${msg.text().slice(0, 150)}`);
    }
  });

  // Collect failed network requests
  page.on('requestfailed', (req) => {
    console.log(`  [request-failed] ${req.method()} ${req.url().slice(0, 100)}`);
  });
}

async function teardown() {
  if (browser) await browser.close();
}

