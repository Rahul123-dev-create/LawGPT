// ─── STEP 3: DOCUMENT UPLOAD ────────────────────────────────────────────

async function testDocumentUpload() {
  console.log('\n══════════════════════════════════════════════════════');
  console.log('  STEP 3: DOCUMENT UPLOAD');
  console.log('══════════════════════════════════════════════════════');

  // Navigate to documents tab
  const currentUrl = page.url();
  const caseMatch = currentUrl.match(/\/app\/case\/([^/]+)/);
  if (!caseMatch) {
    log('Upload: find case ID', 'FAIL', 'Could not extract case ID from URL');
    return false;
  }
  const caseId = caseMatch[1];

  await page.goto(`${BASE_URL}/app/case/${caseId}/documents`, { waitUntil: 'networkidle' });
  await page.waitForTimeout(1000);
  await screenshot('07-documents-tab');

  // Click "Add documents" or "Upload the first document" button
  const addBtn = page.locator('button').filter({ hasText: /Add documents|Upload the first document/ }).first();
  if (await addBtn.isVisible()) {
    await addBtn.click();
    log('Upload: click add documents', 'PASS');
    await page.waitForTimeout(500);
  } else {
    log('Upload: click add documents', 'FAIL', 'Button not found');
    return false;
  }

  // Use the shared legal PDF fixture (real embedded text so the pipeline
  // can extract pages and mark the document 'completed').
  const testPdfPath = FIXTURE_PDF_PATH;
  mkdirSync(join(__dirname, '..', 'test-screenshots'), { recursive: true });

  // Upload the file via the file input
  const fileInput = page.locator('input[type="file"]').first();
  await fileInput.setInputFiles(testPdfPath);
  log('Upload: select test PDF', 'PASS', FIXTURE_PDF);

  await page.waitForTimeout(500);
  await screenshot('08-file-selected');

  // Click Upload button
  const uploadBtn = page.locator('button').filter({ hasText: /Upload \d/ }).first();
  if (await uploadBtn.isVisible()) {
    await uploadBtn.click();
    log('Upload: click upload button', 'PASS');

    // Wait for upload to complete
    try {
      await page.waitForResponse(
        (resp) => resp.url().includes('/documents') && resp.status() === 200,
        { timeout: 15000 }
      );
      log('Upload: upload request completed', 'PASS');
    } catch {
      log('Upload: upload request completed', 'FAIL', 'Timeout waiting for upload response');
    }
  } else {
    log('Upload: click upload button', 'FAIL', 'Upload button not found');
  }

  await page.waitForTimeout(2000);
  await screenshot('09-after-upload');

  // Check for document in list
  const docItem = page.locator(`text=${FIXTURE_PDF}`).first();
  if (await docItem.isVisible()) {
    log('Upload: document appears in list', 'PASS', FIXTURE_PDF);
  } else {
    log('Upload: document appears in list', 'FAIL', 'Document not visible in list');
    await screenshot('09-doc-not-in-list');
  }

  // ── Poll the status badge until the document is 'completed' ──────────────
  // The Documents tab re-polls the API every 4s while a doc is pending or
  // processing, so the badge text in the row is our source of truth. Note:
  // the app's Badge component renders a <div> (not <span>) and its classes
  // don't contain the literal word "badge", so we match direct children of
  // the document row whose trimmed text is exactly a terminal status.
  let finalStatus = 'pending';
  try {
    const handle = await page.waitForFunction(
      (fname) => {
        const nodes = Array.from(document.querySelectorAll('div'));
        for (const node of nodes) {
          const text = node.textContent || '';
          if (text.includes(fname)) {
            const kids = Array.from(node.children);
            for (const kid of kids) {
              const t = (kid.textContent || '').trim().toLowerCase();
              if (t === 'completed' || t === 'failed') return t;
            }
          }
        }
        return false;
      },
      FIXTURE_PDF,
      { timeout: 240000 }
    );
    finalStatus = await handle.jsonValue();
  } catch {
    /* timeout → finalStatus stays 'pending' */
  }

  if (finalStatus === 'completed') {
    log('Upload: processing badge pending → completed', 'PASS');
  } else if (finalStatus === 'failed') {
    log('Upload: processing badge pending → completed', 'FAIL', 'Pipeline marked the fixture as failed');
  } else {
    log('Upload: processing badge pending → completed', 'FAIL', `Document stuck at '${finalStatus}' after 180s`);
  }

  await screenshot('09-document-completed');

  return caseId;
}

