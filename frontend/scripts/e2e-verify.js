// ─── STEP 8: PDF BRIEF EXPORT ──────────────────────────────────────────

async function testPdfExport(caseId) {
  console.log('\n══════════════════════════════════════════════════════');
  console.log('  STEP 8: PDF BRIEF EXPORT');
  console.log('══════════════════════════════════════════════════════');

  await page.goto(`${BASE_URL}/app/case/${caseId}/reports`, { waitUntil: 'networkidle' });
  await page.waitForTimeout(1000);
  await screenshot('18-reports-tab');

  // Test the API endpoint directly (since the PDF download triggers a blob)
  const bodyText = await page.textContent('body');
  const hasReportTab = bodyText.includes('Case Report') || bodyText.includes('Report') || bodyText.includes('Download');
  log('Reports: tab loaded', hasReportTab ? 'PASS' : 'FAIL');

  // Test the PDF endpoint via API with auth
  const loginResp = await page.evaluate(async () => {
    const resp = await fetch('http://localhost:5000/api/auth/login', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email: 'test@lawgpt.local', password: 'Password@123' }),
      credentials: 'include',
    });
    return resp.json();
  });

  const accessToken = loginResp?.data?.accessToken;
  if (!accessToken) {
    log('PDF: get access token', 'FAIL', 'Could not get access token');
    return;
  }
  log('PDF: get access token', 'PASS');

  // Get the case ID from the URL
  const pdfResp = await page.evaluate(async ({ caseId, token }) => {
    const resp = await fetch(`http://localhost:5000/api/cases/${caseId}/report/pdf`, {
      headers: { Authorization: `Bearer ${token}` },
      credentials: 'include',
    });
    return {
      status: resp.status,
      contentType: resp.headers.get('content-type'),
      size: resp.headers.get('content-length'),
    };
  }, { caseId, token: accessToken });

  if (pdfResp.status === 200 && pdfResp.contentType?.includes('application/pdf')) {
    log('PDF: generate report', 'PASS', `Status: ${pdfResp.status}, Content-Type: ${pdfResp.contentType}`);
  } else {
    log('PDF: generate report', 'FAIL', `Status: ${pdfResp.status}, Content-Type: ${pdfResp.contentType}`);
  }

  // Also test metadata endpoint
  const metaResp = await page.evaluate(async ({ caseId, token }) => {
    const resp = await fetch(`http://localhost:5000/api/cases/${caseId}/report/metadata`, {
      headers: { Authorization: `Bearer ${token}` },
      credentials: 'include',
    });
    return resp.json();
  }, { caseId, token: accessToken });

  if (metaResp?.data?.sections) {
    log('PDF: metadata endpoint', 'PASS', `${metaResp.data.sections.length} sections, ${metaResp.data.completeness}% complete`);
  } else {
    log('PDF: metadata endpoint', 'FAIL', 'No sections data');
  }

  // Click the download button in the UI
  const downloadBtn = page.locator('button').filter({ hasText: /Download.*PDF|Download PDF/ }).first();
  if (await downloadBtn.isVisible()) {
    log('Reports: download button visible', 'PASS');
  } else {
    log('Reports: download button visible', 'FAIL', 'Download button not found');
  }

  await screenshot('19-reports-complete');
}

